export default function JourneyGame() {
  const [history, setHistory] = useState([{ node: 1, beans: 1 }]);
  const scrollRef = useRef(null);

  const currentState = history[history.length - 1];
  const currentNodeId = currentState.node;
  const cacaoBeans = currentState.beans;

  const nodeData = gameData[currentNodeId];

  // Scroll to top when node changes
  useEffect(() => {
    if (scrollRef.current) {
      scrollRef.current.scrollIntoView({ behavior: 'smooth' });
    }
  }, [currentNodeId]);

  const handleChoice = (nextNode) => {
    const nextNodeData = gameData[nextNode];
    const newBeans = Math.max(0, cacaoBeans + (nextNodeData.cacaoChange || 0)); // Ensure we don't go below 0
    
    setHistory(prevHistory => [...prevHistory, { node: nextNode, beans: newBeans }]);
  };

  const handleBack = () => {
    if (history.length > 1) {
      setHistory(prevHistory => prevHistory.slice(0, -1));
    }
  };

  const handleRestart = () => {
    setHistory([{ node: 1, beans: 1 }]);
  };

  return (
    <div className="min-h-screen bg-stone-100 font-sans text-stone-800" dir="rtl">
      {/* Header Area */}
      <header className="bg-emerald-800 text-white p-4 shadow-lg sticky top-0 z-10">
        <div className="max-w-2xl mx-auto flex justify-between items-center">
          <div className="flex items-center gap-2">
            <Leaf className="w-5 h-5 text-emerald-300" />
            <h1 className="font-bold text-lg md:text-xl">המסע לפוארטו וייחו</h1>
          </div>
          <div className="bg-amber-100 text-amber-900 px-4 py-2 rounded-full font-bold shadow-inner flex items-center gap-2">
            <span>{cacaoBeans}</span>
            <span>פולי קקאו</span>
            <span className="text-xl">🍫</span>
          </div>
        </div>
      </header>

      {/* Main Content Area */}
      <main className="max-w-2xl mx-auto p-4 py-8" ref={scrollRef}>
        
        {/* Story Card */}
        <div className="bg-white rounded-2xl shadow-xl overflow-hidden border border-stone-200">
          
          <div className="bg-emerald-50 border-b border-emerald-100 p-4">
            <h2 className="text-xl font-bold text-emerald-900">{nodeData.title}</h2>
          </div>

          <div className="p-6 md:p-8 space-y-4">
            
            {/* Cacao Alert if exists on this node */}
            {nodeData.cacaoMessage && (
              <div className={`p-4 rounded-xl flex items-start gap-3 mb-6 ${nodeData.cacaoChange > 0 ? 'bg-amber-50 border border-amber-200 text-amber-900' : 'bg-red-50 border border-red-200 text-red-900'}`}>
                <div className="mt-1">
                  {nodeData.cacaoChange > 0 ? <Award className="w-5 h-5 text-amber-600" /> : <div className="w-5 h-5 flex items-center justify-center font-bold text-red-600">-</div>}
                </div>
                <p className="font-bold">{nodeData.cacaoMessage}</p>
              </div>
            )}

            {/* Story Text */}
            <div className="text-lg leading-relaxed text-stone-700 space-y-4">
              {nodeData.text.map((paragraph, idx) => (
                <p key={idx}>{paragraph}</p>
              ))}
            </div>

            {/* End Game Status */}
            {nodeData.isEnd && (
              <div className="mt-8 p-6 bg-stone-50 rounded-xl text-center border-2 border-stone-200">
                <h3 className="text-2xl font-bold text-emerald-800 mb-2">סוף המסע</h3>
                <p className="text-stone-600 mb-4">הגעת לסוף המסלול שלך. שמרת על {cacaoBeans} פולי קקאו לאורך הדרך.</p>
                <button 
                  onClick={handleRestart}
                  className="mx-auto flex items-center gap-2 bg-emerald-600 hover:bg-emerald-700 text-white px-6 py-3 rounded-xl shadow-md transition transform hover:-translate-y-1"
                >
                  <RotateCcw className="w-5 h-5" />
                  התחל מחדש
                </button>
              </div>
            )}

            {/* Choices */}
            {!nodeData.isEnd && (
              <div className="mt-8 pt-6 border-t border-stone-100 flex flex-col gap-3">
                {nodeData.choices.map((choice, idx) => (
                  <button
                    key={idx}
                    onClick={() => handleChoice(choice.next)}
                    className="w-full text-right p-4 rounded-xl bg-emerald-700 hover:bg-emerald-800 text-white shadow-md transition transform hover:-translate-y-1 flex items-center justify-between group"
                  >
                    <span className="text-lg pl-4 leading-snug">{choice.text}</span>
                    <ArrowLeft className="w-6 h-6 opacity-70 group-hover:opacity-100 group-hover:-translate-x-1 transition-all shrink-0" />
                  </button>
                ))}
              </div>
            )}
            
          </div>
        </div>

        {/* Footer Controls */}
        <div className="mt-6 flex justify-between items-center text-sm font-medium">
          {history.length > 1 ? (
            <button 
              onClick={handleBack}
              className="flex items-center gap-2 text-stone-500 hover:text-stone-800 transition px-4 py-2 rounded-lg hover:bg-stone-200"
            >
              <ArrowRight className="w-4 h-4" />
              חזור שלב אחורה
            </button>
          ) : (
            <div></div> /* Empty div to keep flex layout balanced */
          )}
          
          {!nodeData.isEnd && (
            <button 
              onClick={handleRestart}
              className="flex items-center gap-2 text-stone-500 hover:text-red-600 transition px-4 py-2 rounded-lg hover:bg-red-50"
            >
              <RotateCcw className="w-4 h-4" />
              התחל מחדש
            </button>
          )}
        </div>
      </main>
    </div>
  );
}
